const bookingMessage = "Hello, I would like to reserve one table for 10 guests at Maward Al Yasmeen on Tuesday, 1 September 2026, at 8:00 PM. We are a mixed Saudi-Chinese company group. Please arrange one table in the family section and confirm the reservation.";

let currentLanguage = localStorage.getItem("team-night-language") || "zh";

function translatePage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.innerHTML = translations[language][key];
  });
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === language);
  });
  localStorage.setItem("team-night-language", language);
  updateBudget();
  updateCountdown();
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => translatePage(button.dataset.language));
});

const dessertToggle = document.querySelector("[data-dessert-toggle]");
function updateBudget() {
  const total = dessertToggle.checked ? 1975 : 1915;
  const remaining = 2000 - total;
  document.querySelector("[data-total]").textContent = total.toLocaleString("en-US");
  document.querySelector("[data-per-person]").textContent = (total / 10).toFixed(1);
  const budgetBar = document.querySelector("[data-budget-bar]");
  budgetBar.style.width = `${Math.min((total / 2000) * 100, 100)}%`;
  budgetBar.style.background = remaining >= 0 ? "var(--mint)" : "var(--signal)";
  const statusKey = remaining >= 0 ? "withinBudget" : "overBudget";
  document.querySelector("[data-budget-status]").textContent = translations[currentLanguage][statusKey].replace("{amount}", Math.abs(remaining));
}
dessertToggle.addEventListener("change", updateBudget);

function showToast(message) {
  const toast = document.querySelector("[data-toast]");
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.setTimeout(() => toast.classList.remove("is-visible"), 2300);
}

document.querySelector("[data-copy-booking]").addEventListener("click", async () => {
  try {
    await navigator.clipboard.writeText(bookingMessage);
    showToast(translations[currentLanguage].copied);
  } catch {
    showToast(translations[currentLanguage].copyFailed);
  }
});

document.querySelectorAll("[data-check]").forEach((checkbox) => {
  const storageKey = `team-night-check-${checkbox.dataset.check}`;
  checkbox.checked = localStorage.getItem(storageKey) === "true";
  checkbox.addEventListener("change", () => localStorage.setItem(storageKey, checkbox.checked));
});

function updateCountdown() {
  const eventDate = new Date("2026-09-01T18:00:00+03:00");
  const eventEnd = new Date("2026-09-01T22:00:00+03:00");
  const now = new Date();
  const riyadhDate = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Riyadh",
    year: "numeric",
    month: "2-digit",
    day: "2-digit"
  }).format(now);
  const difference = eventDate - now;
  let label;
  if (now > eventEnd) {
    label = translations[currentLanguage].countdownDone;
  } else if (riyadhDate === "2026-09-01" || difference <= 0) {
    label = translations[currentLanguage].countdownToday;
  } else {
    const days = Math.ceil(difference / 86400000);
    label = days === 1 ? translations[currentLanguage].countdownTomorrow : translations[currentLanguage].countdownDays.replace("{days}", days);
  }
  document.querySelector("[data-countdown]").textContent = label;
}

translatePage(currentLanguage);
